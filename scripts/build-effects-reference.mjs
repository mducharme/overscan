#!/usr/bin/env node
/**
 * Writes docs/EFFECTS.md from the node settings schemas in @overscan/nodes.
 * Requires a prior `pnpm build`. Run with `pnpm build-effects-reference`.
 */
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..')
const { NODE_SCHEMAS } = await import(pathToFileURL(join(ROOT, 'packages', 'nodes', 'dist', 'schema', 'index.js')).href)

const KINDS = [
  ['generator', 'Generators', 'Draw an image from nothing.'],
  ['modifier', 'Modifiers', 'Take one image (input `in`) and transform it.'],
  ['compositor', 'Compositors', 'Combine several images.'],
  ['signal', 'Signals', 'Produce numbers that other nodes can use as `{ "node": id, "output": name }`.'],
]

const code = v => '`' + String(v).replace(/`/g, "'") + '`'
const cell = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')

function typeOf(p) {
  switch (p.type) {
    case 'number': return p.animatable ? 'number, animatable' : 'number'
    case 'enum': return (p.open ? 'one of (or any string): ' : 'one of: ') + p.options.map(code).join(', ')
    case 'color': return p.allow?.length ? `colour or ${p.allow.filter(Boolean).map(code).join(', ')}` : 'colour'
    case 'palette': return 'palette'
    case 'asset': return `${p.kind} file`
    default: return p.type
  }
}

function defaultOf(p) {
  if (!('default' in p) || p.default === undefined || p.default === '') return '—'
  const json = JSON.stringify(p.default)
  return code(json.length > 40 ? json.slice(0, 37) + '…' : json)
}

function rangeOf(p) {
  if (p.min === undefined && p.max === undefined) return ''
  return `${p.min ?? '…'} – ${p.max ?? '…'}`
}

const schemas = Object.values(NODE_SCHEMAS)
const out = [
  '# Effects reference',
  '',
  '<!-- Generated by scripts/build-effects-reference.mjs from the schemas in packages/nodes/src/schema. Do not edit by hand. -->',
  '',
  `Every built-in node (${schemas.length} in total) and its config options. Use the \`impl\` name in a scene's graph. Options marked *animatable* also accept \`{ "track": name }\` or \`{ "node": id, "output": name }\`.`,
  '',
]
for (const [kind, title, blurb] of KINDS) {
  const list = schemas.filter(s => s.kind === kind).sort((a, b) => a.impl.localeCompare(b.impl))
  out.push(`- [${title}](#${title.toLowerCase()}): ${list.map(s => `[${s.impl}](#${s.impl})`).join(', ')}`)
}
for (const [kind, title, blurb] of KINDS) {
  out.push('', `## ${title}`, '', blurb)
  for (const s of schemas.filter(x => x.kind === kind).sort((a, b) => a.impl.localeCompare(b.impl))) {
    out.push('', `### ${s.impl}`, '', `**${s.label}.** ${s.description}`)
    if (s.inputs?.length) out.push('', `Inputs: ${s.inputs.map(code).join(', ')}.`)
    if (s.outputs?.length) out.push('', `Outputs: ${s.outputs.map(code).join(', ')}.`)
    const params = Object.entries(s.params)
    if (params.length) {
      out.push('', '| Option | Type | Default | Range | Description |', '| --- | --- | --- | --- | --- |')
      for (const [key, p] of params) out.push(`| ${code(key)} | ${cell(typeOf(p))} | ${defaultOf(p)} | ${rangeOf(p)} | ${cell(p.description)} |`)
    }
    if (s.deprecated?.length) out.push('', `Ignored (kept for compatibility): ${s.deprecated.map(code).join(', ')}.`)
  }
}
await writeFile(join(ROOT, 'docs', 'EFFECTS.md'), out.join('\n') + '\n')
console.log(`build-effects-reference: wrote docs/EFFECTS.md (${schemas.length} nodes)`)

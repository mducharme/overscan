#!/usr/bin/env node
/**
 * Writes docs/EXAMPLES.md: every built-in effect with its example scene and previews (from
 * `pnpm export-example-gifs`), extra examples under the effect they show, the advanced compositions and
 * the showcase demo. Descriptions come from the node schemas in @overscan/nodes (run `pnpm build` first).
 */
import { existsSync } from 'node:fs'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..')
const { NODE_SCHEMAS } = await import(join(ROOT, 'packages', 'nodes', 'dist', 'index.js'))

const KINDS = [
  { kind: 'generator', dir: 'generators', title: 'Generators', intro: 'Draw an image from nothing.' },
  { kind: 'modifier', dir: 'modifiers', title: 'Modifiers', intro: 'Change the image fed into them.' },
  { kind: 'compositor', dir: 'compositors', title: 'Compositors', intro: 'Combine two or more images.' },
  { kind: 'signal', dir: 'signals', title: 'Signals', intro: 'Produce numbers that drive other nodes’ settings.' },
]

const readJson = async path => JSON.parse(await readFile(path, 'utf8'))
const scenesIn = async dir => (await readdir(join(ROOT, 'examples', dir))).filter(f => f.endsWith('.scene.json')).sort()
// GitHub's heading anchors: lower case, punctuation dropped, every space a hyphen.
const anchor = text => text.toLowerCase().replace(/[^a-z0-9 -]/g, '').trim().replace(/ /g, '-')

/** The two previews of an example, if they were exported. */
function previews(dir, name, alt) {
  const ansi = `examples/${dir}/${name}-ansi.gif`
  const full = `examples/${dir}/${name}.gif`
  if (!existsSync(join(ROOT, 'docs', ansi)) || !existsSync(join(ROOT, 'docs', full))) return '_No preview yet: run `pnpm export-example-gifs ' + name + '`._\n'
  return `| Terminal (ANSI, 80×24) | Full resolution |\n| :---: | :---: |\n| ![${alt} in the terminal](${ansi}) | ![${alt}](${full}) |\n`
}

const sceneLink = (dir, file) => `[\`examples/${dir}/${file}\`](../examples/${dir}/${file})`
const runLine = (dir, file) => `\`pnpm run overscan -- run examples/${dir}/${file}\``

const out = []
out.push('# Examples gallery', '')
out.push('<!-- Generated by scripts/build-examples-doc.mjs. Do not edit by hand: `pnpm build && pnpm export-example-gifs && pnpm build-examples-doc`. -->', '')
const total = Object.keys(NODE_SCHEMAS).length
out.push(`Every built-in effect (${total} in total) has an example scene, shown here as the terminal draws it (ANSI half-blocks on an 80×24 grid) and at full resolution. Option tables for each effect are in [EFFECTS.md](EFFECTS.md).`, '')
out.push('Play any example in the terminal with `pnpm run overscan -- run <scene>`, or open it in the studio with `pnpm run overscan -- dev <scene>`.', '')

// Group the examples: each effect's own scene, plus extra scenes under the effect they demonstrate.
const groups = []
for (const k of KINDS) {
  const schemas = Object.values(NODE_SCHEMAS).filter(s => s.kind === k.kind).sort((a, b) => a.impl.localeCompare(b.impl))
  const extras = new Map()
  for (const file of await scenesIn(k.dir)) {
    const name = file.replace(/\.scene\.json$/, '')
    if (NODE_SCHEMAS[name]) continue
    const scene = await readJson(join(ROOT, 'examples', k.dir, file))
    const main = scene.graph.nodes.find(n => n.type === k.kind && NODE_SCHEMAS[n.impl])
    if (!main) continue
    extras.set(main.impl, [...(extras.get(main.impl) ?? []), { file, name, title: scene.title }])
  }
  groups.push({ ...k, schemas, extras })
}
const advanced = []
for (const file of await scenesIn('advanced')) {
  const scene = await readJson(join(ROOT, 'examples', 'advanced', file))
  advanced.push({ file, name: file.replace(/\.scene\.json$/, ''), scene })
}
const showcase = await readJson(join(ROOT, 'examples', 'showcase.demo.json'))

out.push('## Contents', '')
out.push(`- [Showcase demo](#showcase-demo)`)
for (const g of groups) out.push(`- [${g.title}](#${anchor(g.title)}) (${g.schemas.length}): ${g.schemas.map(s => `[${s.impl}](#${anchor(`${s.label} ${s.impl}`)})`).join(', ')}`)
out.push(`- [Advanced compositions](#advanced-compositions) (${advanced.length})`, '')

// Showcase: the section list, so readers see what plays when.
out.push('## Showcase demo', '')
out.push(`[\`examples/showcase.demo.json\`](../examples/showcase.demo.json): **${showcase.title}**, ${showcase.sections.length} sections cut to a synthesised soundtrack (\`${showcase.audio}\`, built by \`scripts/build-showcase-music.mjs\`). Play it with \`pnpm run overscan -- run examples/showcase.demo.json\` (audio needs \`mpv\`) or open it in the studio.`, '')
out.push('| # | Section | Effects | Into the next |', '| ---: | --- | --- | --- |')
for (const [i, section] of showcase.sections.entries()) {
  const scene = await readJson(join(ROOT, 'examples', section.scene))
  const impls = [...new Set(scene.graph.nodes.map(n => n.impl))].map(impl => `\`${impl}\``).join(', ')
  out.push(`| ${i + 1} | [${section.id}](../examples/${section.scene.replace(/^\.\//, '')}) | ${impls} | ${section.transition ? `${section.transition.type} ${section.transition.duration} s` : '—'} |`)
}
out.push('', `Demo-wide modifiers: ${(showcase.modifiers ?? []).map(m => `\`${m.impl}\``).join(', ') || 'none'}.`, '')

for (const g of groups) {
  out.push(`## ${g.title}`, '', g.intro, '')
  for (const schema of g.schemas) {
    const file = `${schema.impl}.scene.json`
    out.push(`### ${schema.label} (\`${schema.impl}\`)`, '')
    out.push(schema.description, '')
    out.push(previews(g.dir, schema.impl, schema.label))
    out.push(`${sceneLink(g.dir, file)} · ${runLine(g.dir, file)} · [options](EFFECTS.md#${schema.impl})`, '')
    for (const extra of g.extras.get(schema.impl) ?? []) {
      out.push(`#### ${extra.title}`, '')
      out.push(previews(g.dir, extra.name, extra.title))
      out.push(`${sceneLink(g.dir, extra.file)} · ${runLine(g.dir, extra.file)}`, '')
    }
  }
}

out.push('## Advanced compositions', '', 'Several effects wired together; the chain lists each scene’s nodes in graph order.', '')
for (const a of advanced) {
  out.push(`### ${a.scene.title}`, '')
  out.push(`Nodes: ${a.scene.graph.nodes.map(n => `\`${n.impl}\``).join(' · ')}`, '')
  out.push(previews('advanced', a.name, a.scene.title))
  out.push(`${sceneLink('advanced', a.file)} · ${runLine('advanced', a.file)}`, '')
}

out.push('## See also', '', '- [Effects reference](EFFECTS.md): every option of every effect', '- [Scene format](scene-format.md)', '- [Graph model](graph-model.md)', '')
await writeFile(join(ROOT, 'docs', 'EXAMPLES.md'), out.join('\n'))
console.log(`build-examples-doc: wrote docs/EXAMPLES.md (${total} effects, ${advanced.length} advanced, showcase)`)
